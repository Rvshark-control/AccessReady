import type { ClinicMatchResult, RequirementId } from "@/types/api";
import { requirementLabel } from "@/utils/requirements";
import { getMatchStatusMeta } from "@/utils/status";

/**
 * Plain-text accommodation checklist for copying or downloading.
 * Built only from the backend's match result plus the patient's own selections.
 */
export function buildChecklistText(
  result: ClinicMatchResult,
  needs: readonly RequirementId[],
  preparedOn: Date,
): string {
  const status = getMatchStatusMeta(result.status);
  const confirmed = result.checks.filter((c) => c.status === "CONFIRMED");
  const date = preparedOn.toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  const lines: string[] = [
    "ACCESSREADY ACCOMMODATION CHECKLIST",
    "===================================",
    "",
    `Clinic: ${result.clinicName} (fictional demonstration clinic)`,
    `Prepared: ${date}`,
    "",
    "MY ACCESSIBILITY NEEDS",
    ...needs.map((id) => `- ${requirementLabel(id)}`),
    "",
    `COMPATIBILITY STATUS (demonstration data): ${status.label.toUpperCase()}`,
    `Confirmed: ${result.confirmedCount}   Unavailable: ${result.unavailableCount}   Unknown: ${result.unknownCount}`,
    "",
    "QUESTIONS TO ASK THE CLINIC",
  ];

  if (result.verificationQuestions.length > 0) {
    result.verificationQuestions.forEach((question, i) => {
      lines.push(`${i + 1}. ${question}`);
      lines.push("   Answer: ______________________________________________");
    });
  } else {
    lines.push("No open questions in the demonstration data.");
    lines.push("Confirm your accommodations when you book. Records can change.");
  }

  if (confirmed.length > 0) {
    lines.push("", "CONFIRMED IN THE DEMO RECORD (mention these when you book)");
    for (const check of confirmed) lines.push(`- ${requirementLabel(check.requirement)}`);
  }

  lines.push(
    "",
    "-----------------------------------",
    "This checklist was generated by the AccessReady prototype from fictional",
    "demonstration data. It is not a guarantee of real-world accessibility.",
    "AccessReady has not contacted this clinic or sent any message for you.",
    "",
  );

  return lines.join("\n");
}

/** Just the questions, ready to paste into an email, a patient portal message, or notes. */
export function buildQuestionsText(result: ClinicMatchResult): string {
  if (result.verificationQuestions.length === 0) {
    return `No open accessibility questions for ${result.clinicName} in the AccessReady demonstration data.\n`;
  }
  return [
    `Accessibility questions for ${result.clinicName}:`,
    "",
    ...result.verificationQuestions.map((q, i) => `${i + 1}. ${q}`),
    "",
  ].join("\n");
}

export function checklistFileName(clinicName: string): string {
  const slug = clinicName
    .toLowerCase()
    .replace(/\[[^\]]*\]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return `accessready-checklist-${slug || "clinic"}.txt`;
}
